// Copies the shared page-content contracts from ../backend/src/contracts so the
// panel validates exactly what the API validates. The backend is the source of
// truth; never edit src/contracts by hand.
import { cpSync, existsSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const from = path.resolve(root, '../backend/src/contracts');
const to = path.resolve(root, 'src/contracts');

if (!existsSync(from)) {
  if (existsSync(to)) {
    console.log('[sync-contracts] backend not present, using committed copy');
    process.exit(0);
  }
  console.error(`[sync-contracts] ${from} not found`);
  process.exit(1);
}
// Copy in place (never delete the folder): running dev servers keep watching it.
cpSync(from, to, { recursive: true });
if (existsSync(to)) {
  const keep = new Set([...readdirSync(from), 'README.md']);
  for (const f of readdirSync(to)) if (!keep.has(f)) rmSync(path.join(to, f), { recursive: true, force: true });
}
writeFileSync(
  path.join(to, 'README.md'),
  'Generated by `npm run sync:contracts` from ../backend/src/contracts — do not edit here.\n',
);
console.log('[sync-contracts] contracts synced');
